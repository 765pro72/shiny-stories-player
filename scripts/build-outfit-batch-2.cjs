// Check newlines
let newlineErrors = 0;
const result = [];
const mapResult = {};

for (let i = 0; i < items.length; i++) {
  const item = items[i];
  const tr = translations[i];
  const origNl = (item.text.match(/\n/g) || []).length;
  const trNl = (tr.match(/\n/g) || []).length;
  if (origNl !== trNl) {
    console.error(`Newline mismatch at item ${i} (${item.idol} ${item.id}): expected ${origNl}, got ${trNl}`);
    console.error(`ORIG: ${JSON.stringify(item.text)}`);
    console.error(`TR  : ${JSON.stringify(tr)}`);
    newlineErrors++;
  }
  result.push({
    idol: item.idol,
    id: item.id,
    text: item.text,
    translation: tr
  });
  mapResult[item.text] = tr;
}

if (newlineErrors > 0) {
  console.error(`Total newline errors: ${newlineErrors}`);
  process.exit(1);
}

