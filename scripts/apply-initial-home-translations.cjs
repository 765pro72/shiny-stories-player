['public/home-assets/catalog.json', 'data/home-catalog.json'].forEach(file => {
  const cat = JSON.parse(fs.readFileSync(file, 'utf8'));
  let updated = 0;
  for (const idol of cat) {
    for (const v of (idol.voices || [])) {
      if (data[v.id]) {
        const item = data[v.id];
        v.original = item.orig;
        v.translation = item.trans;
        v.speaker = item.spk;
        v.translationSource = 'AI 听写与直译（用户 m00944 授权）';
        updated++;
      }
    }
  }
  fs.writeFileSync(file, JSON.stringify(cat, null, 2));
  console.log(`Updated ${updated} voices in ${file}`);
});
