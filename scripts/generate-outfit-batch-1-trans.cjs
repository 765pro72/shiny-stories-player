let missing = 0;
let lineMismatch = 0;

for (let i = 0; i < batch1.length; i++) {
  const item = batch1[i];
  const tr = translations[item.text];
  if (!tr) {
    console.error(`Missing translation for index ${i}:`, item.text);
    missing++;
    continue;
  }
  const origLines = item.text.split('\n').length;
  const trLines = tr.split('\n').length;
  if (origLines !== trLines) {
    console.error(`Line break mismatch at ${i}: orig=${origLines}, tr=${trLines}`);
    console.error('Orig:', JSON.stringify(item.text));
    console.error('Tr:  ', JSON.stringify(tr));
    lineMismatch++;
  }
}

console.log(`Validation result: Total items=${batch1.length}, Missing=${missing}, LineBreakMismatches=${lineMismatch}`);

if (missing === 0 && lineMismatch === 0) {
  const outPath = 'f:/sc/scripts/outfit-batch-1-translated.json';
  fs.writeFileSync(outPath, JSON.stringify(translations, null, 2), 'utf8');
  console.log(`Saved ${Object.keys(translations).length} translations to ${outPath}`);
} else {
  process.exit(1);
}
