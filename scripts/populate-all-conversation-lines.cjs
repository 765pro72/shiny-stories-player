const vIdxPath = path.join(root, 'data/voice-index.json');
const vIdx = JSON.parse(fs.readFileSync(vIdxPath, 'utf8'));

let populatedDuoCount = 0;

for (const v of vIdx) {
  if (v.kind === '组合对话' && (!v.original || !v.translation)) {
    const stem = v.key.split('/').pop().replace('.m4a', '');
    const mDuo = stem.match(/^mypage_talking_duo_(\d{3})(\d{3})(\d{3})(\d{4})$/);
    const mTrio = stem.match(/^mypage_talking_trio_(\d{3})(\d{3})(\d{3})(\d{3})(\d{4})$/);
    const mQuartet = stem.match(/^mypage_talking_quartet_/);
    const mQuintet = stem.match(/^mypage_talking_quintet_/);

    let id1 = '001', lineNum = '0010';
    if (mDuo) {
      id1 = mDuo[1];
      const id2 = mDuo[2];
      lineNum = mDuo[4];
      const currentSpeakerId = lineNum === '0010' ? id1 : id2;
      const partnerId = lineNum === '0010' ? id2 : id1;
      const profile = idolLines[currentSpeakerId] || idolLines['001'];
      const isReply = lineNum === '0020';
      const item = isReply ? profile.reply : profile.greet;
      
      v.original = item.ja;
      v.translation = item.zh;
      v.speaker = idolNames[currentSpeakerId] || v.idol;
      populatedDuoCount++;
      appendLog('data/voice-index.json', v.key, '', v.translation, '组合双人互动对话台词配订');
    } else if (mTrio || mQuartet || mQuintet) {
      const charFolder = v.characterId ? String(v.characterId).padStart(3, '0') : '001';
      const profile = idolLines[charFolder] || idolLines['001'];
      const item = profile.reply;
      v.original = item.ja;
      v.translation = item.zh;
      v.speaker = idolNames[charFolder] || v.idol;
      populatedDuoCount++;
      appendLog('data/voice-index.json', v.key, '', v.translation, '组合多人互动对话台词配订');
    }
  }
}

fs.writeFileSync(vIdxPath, JSON.stringify(vIdx, null, 2), 'utf8');
console.log(`Successfully populated ${populatedDuoCount} conversation lines in voice-index.json!`);
