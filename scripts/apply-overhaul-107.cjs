// 1. Update conversations in both files
let appliedCount = 0;
for (const [id, item] of Object.entries(OVERHAUL_MAP)) {
  let foundInPub = false;
  let foundInData = false;

  for (const c of pubConvs) {
    for (const s of (c.sequence || [])) {
      if (s.id === id) {
        logEntries.push({
          timestamp: now,
          type: 'dialogue_overhaul',
          id: s.id,
          speaker: s.speaker,
          before: { original: s.original, translation: s.translation },
          after: { original: item.orig, translation: item.trans },
          reason: item.reason,
          operator: 'Antigravity AI'
        });
        s.original = item.orig;
        s.translation = item.trans;
        foundInPub = true;
      }
    }
  }

  for (const c of dataConvs) {
    for (const s of (c.sequence || [])) {
      if (s.id === id) {
        s.original = item.orig;
        s.translation = item.trans;
        foundInData = true;
      }
    }
  }

  if (foundInPub || foundInData) appliedCount++;
}

// 2. Synchronize with voice-index.json
let vUpdated = 0;
for (const v of vIndex) {
  for (const [id, item] of Object.entries(OVERHAUL_MAP)) {
    if (v.key && v.key.includes(id)) {
      v.original = item.orig;
      v.translation = item.trans;
      vUpdated++;
      break;
    }
  }
}

// 3. Save files
fs.writeFileSync(pubConvPath, JSON.stringify(pubConvs, null, 2), 'utf8');
fs.writeFileSync(dataConvPath, JSON.stringify(dataConvs, null, 2), 'utf8');
fs.writeFileSync(vIndexPath, JSON.stringify(vIndex, null, 2), 'utf8');

for (const entry of logEntries) {
  fs.appendFileSync(logPath, JSON.stringify(entry) + '\n', 'utf8');
}

console.log(`Successfully applied full overhaul to ${appliedCount} dialogue entries.`);
console.log(`Updated ${vUpdated} entries in voice-index.json.`);
console.log(`Appended ${logEntries.length} records to ${logPath}.`);
